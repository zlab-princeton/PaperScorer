"""User-local TeX Live install for compute nodes without pdflatex.

LaTeX-dir reviews (paperprep's compile stage) need pdflatex/latexmk. On many
clusters they're not on PATH and a sysadmin install isn't possible. This
module writes a self-contained install shell script (downloads install-tl-unx
from CTAN, runs `perl install-tl --no-interaction` against a generated
profile, prints the PATH export), optionally executes it, and returns the
resulting bin dir so `cfg.paperprep.texlive_bin` can be set.

scheme-medium is the default — ~1GB, covers the latex/pdflatex/latexmk
toolchain plus the common LaTeX packages arxiv submissions pull in. The full
scheme is ~7GB and takes hours; basic (~150MB) misses packages like cite,
algorithm2e, etc. that surface mid-compile.
"""
from __future__ import annotations

import os
import platform
import shutil
import subprocess
from pathlib import Path

INSTALL_URL = "https://mirror.ctan.org/systems/texlive/tlnet/install-tl-unx.tar.gz"


def pdflatex_works(bin_dir: str | Path | None = None) -> tuple[bool, str]:
    """Return (works, resolved_path). Probes by actually running `pdflatex
    --version`, not just `which` — a binary on PATH can still fail to execute
    (broken install, missing shared lib, wrong glibc).

    bin_dir: when set, look ONLY inside `bin_dir` (don't fall through to the
    rest of $PATH). Use this for "does the override actually have a working
    pdflatex?" probes -- otherwise an invalid override would be reported as
    "works" if pdflatex exists somewhere else on PATH.
    """
    if bin_dir:
        cand = Path(bin_dir).expanduser() / "pdflatex"
        path = str(cand) if cand.exists() else ""
    else:
        path = shutil.which("pdflatex") or ""
    if not path:
        return False, ""
    try:
        r = subprocess.run([path, "--version"], capture_output=True, timeout=10)
        return r.returncode == 0, path
    except (subprocess.TimeoutExpired, OSError):
        # Found but doesn't execute (missing lib, broken symlink, ...)
        return False, path


def inject_bin_into_path(bin_dir: str | Path) -> None:
    """Prepend `bin_dir` to `os.environ["PATH"]` so subprocesses spawned by
    THIS Python process (paperprep-serve, the rest of the wizard, ...) see
    the new toolchain immediately -- the in-process equivalent of sourcing
    ~/.bashrc, which a child can't do for its parent."""
    s = str(bin_dir)
    cur = os.environ.get("PATH", "")
    if s in cur.split(os.pathsep):
        return
    os.environ["PATH"] = f"{s}{os.pathsep}{cur}" if cur else s


def platform_bin_subdir() -> str:
    """install-tl writes binaries under bin/<arch>-linux on Linux."""
    m = platform.machine() or "x86_64"
    return f"{m}-linux"


def bin_dir_for(install_dir: str | Path) -> Path:
    return Path(install_dir).expanduser() / "bin" / platform_bin_subdir()


def script_path(repo_root: Path) -> Path:
    return repo_root / "setup_texlive.sh"


def render_install_script(install_dir: str) -> str:
    """Generate the install shell script. Self-contained, idempotent-ish.

    Uses scheme-medium (~1GB, ~15-30 min) which is the right tradeoff for
    arxiv LaTeX: scheme-basic misses common packages, scheme-full is ~7GB
    and takes hours.
    """
    inst = str(Path(install_dir).expanduser())
    return f"""#!/usr/bin/env bash
# Auto-generated by `paperscorer setup` — installs TeX Live (scheme-medium) into
# a user-local directory. Re-run safely: TL's installer is idempotent for the
# same target dir.
set -euo pipefail

INSTALL_DIR="{inst}"

echo "[texlive] target dir : $INSTALL_DIR"
echo "[texlive] scheme     : medium (~1GB, ~15-30 min on a normal connection)"
echo "[texlive] downloading installer from CTAN..."

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
cd "$TMP"

if command -v curl >/dev/null; then
    curl -fsSL -o install-tl-unx.tar.gz "{INSTALL_URL}"
elif command -v wget >/dev/null; then
    wget -q -O install-tl-unx.tar.gz "{INSTALL_URL}"
else
    echo "[texlive] ERROR: need curl or wget on PATH" >&2
    exit 1
fi

tar xzf install-tl-unx.tar.gz
cd install-tl-2*

cat > texlive.profile <<EOF
selected_scheme scheme-medium
TEXDIR $INSTALL_DIR
TEXMFLOCAL $INSTALL_DIR/texmf-local
TEXMFSYSCONFIG $INSTALL_DIR/texmf-config
TEXMFSYSVAR $INSTALL_DIR/texmf-var
TEXMFCONFIG ~/.texlive/texmf-config
TEXMFVAR ~/.texlive/texmf-var
TEXMFHOME ~/texmf
instopt_adjustpath 0
instopt_adjustrepo 1
tlpdbopt_install_docfiles 0
tlpdbopt_install_srcfiles 0
EOF

echo "[texlive] running install-tl (this is the slow step)..."
perl ./install-tl --no-interaction --profile=texlive.profile

PLATFORM="$(uname -m)-linux"
BIN_DIR="$INSTALL_DIR/bin/$PLATFORM"

echo
echo "[texlive] done — pdflatex now at: $BIN_DIR/pdflatex"
echo
echo "[texlive] add to your PATH:"
echo "    export PATH=$BIN_DIR:\\$PATH"
echo
echo "[texlive] (optional) append to ~/.bashrc:"
echo "    echo 'export PATH=$BIN_DIR:\\$PATH' >> ~/.bashrc"
"""


def write_install_script(repo_root: Path, install_dir: str) -> Path:
    """Materialize the install script under <repo>/setup_texlive.sh."""
    sp = script_path(repo_root)
    sp.write_text(render_install_script(install_dir))
    sp.chmod(0o755)
    return sp


def append_path_to_bashrc(bin_dir: Path) -> bool:
    """Append `export PATH=<bin_dir>:$PATH` to ~/.bashrc if not already there.

    Returns True if the line was added, False if it was already present (or
    ~/.bashrc doesn't exist and we created it).
    """
    bashrc = Path.home() / ".bashrc"
    line = f"export PATH={bin_dir}:$PATH"
    existing = bashrc.read_text() if bashrc.exists() else ""
    if line in existing:
        return False
    sep = "" if (not existing or existing.endswith("\n")) else "\n"
    with bashrc.open("a") as f:
        f.write(f"{sep}# Added by paperscorer setup — TeX Live\n{line}\n")
    return True


def run_install_script(script: Path) -> int:
    """Execute the install script, streaming output. Returns its exit code."""
    proc = subprocess.run(["bash", str(script)])
    return proc.returncode
